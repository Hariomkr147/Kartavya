"""Column helpers, mixins, and the SQLite PRAGMAs the schema depends on.

`backend/database/schema.dbml` is authoritative for every column name, type,
nullability, index and delete rule. Do not improve on it here.
"""

from __future__ import annotations

from datetime import UTC, datetime
from enum import StrEnum
from typing import TypeVar

from sqlalchemy import Engine, event
from sqlalchemy import Enum as SAEnum
from sqlalchemy.orm import Mapped, mapped_column

from app.extensions import db

__all__ = ["db", "TimestampMixin", "enum_column", "utcnow"]

E = TypeVar("E", bound=StrEnum)


def utcnow() -> datetime:
    """Naive UTC — SQLite has no timezone type, so everything stored is UTC.

    Domain functions take `now` as an argument; this is only for column defaults
    and for the places a service genuinely needs the wall clock.
    """
    return datetime.now(UTC).replace(tzinfo=None)


def enum_column(enum_type: type[E], *, name: str | None = None) -> SAEnum:
    """Render a Python enum as a CHECK-constrained VARCHAR.

    `native_enum=False` is what the schema's design note intends: SQLite has no
    ENUM type, so the value set is enforced by a CHECK constraint instead. A
    typo'd status then cannot be stored, which is the whole point of the enums
    in schema.dbml.

    `name` overrides what the constraint is named after. The `ck` naming
    convention is `ck_<table>_<constraint_name>`, and for a CHECK generated by
    an Enum the constraint name is the ENUM's name — not the column's. Two
    columns of the same enum type in one table therefore collide on a single
    constraint name. SQLite accepts that silently; PostgreSQL rejects the whole
    CREATE TABLE with "check constraint ... already exists". Pass a distinct
    name on each such column — see `status_history.from_status` / `to_status`,
    the only place in this schema where it happens, and
    `tests/unit/test_schema_constraints.py`, which fails if another appears.
    """
    # Passing `name=None` is NOT the same as omitting it: an explicit None
    # suppresses the name SQLAlchemy would otherwise derive from the enum
    # class, leaving every CHECK unnamed and the ck_ convention with nothing to
    # interpolate. Only pass the keyword when there is a name to pass.
    overrides = {} if name is None else {"name": name}
    return SAEnum(
        enum_type,
        **overrides,
        native_enum=False,
        # SQLAlchemy 1.4+ defaults this to False, which renders a BARE VARCHAR
        # and silently drops the CHECK this function exists to produce. It must
        # stay explicit — see migrations/README.md, hand-check 2.
        create_constraint=True,
        validate_strings=True,
        length=40,
        values_callable=lambda e: [member.value for member in e],
    )


class TimestampMixin:
    """`created_at` on everything; `updated_at` only where the schema has it."""

    created_at: Mapped[datetime] = mapped_column(default=utcnow, nullable=False)


@event.listens_for(Engine, "connect")
def _set_sqlite_pragmas(dbapi_connection, _connection_record) -> None:
    """Turn on the guarantees SQLite disables by default.

    Without `foreign_keys=ON`, every RESTRICT and CASCADE rule in schema.dbml is
    silently inert — deletes that the schema is supposed to block succeed, and
    the audit trails this system is built around can be orphaned.

    Guarded by a driver check so a future Postgres move does not break here.
    """
    if type(dbapi_connection).__module__.split(".")[0] != "sqlite3":
        return
    cursor = dbapi_connection.cursor()
    cursor.execute("PRAGMA foreign_keys=ON")
    cursor.execute("PRAGMA journal_mode=WAL")  # readers do not block on a writer
    cursor.execute("PRAGMA busy_timeout=5000")  # wait for a lock, do not fail instantly
    cursor.close()
