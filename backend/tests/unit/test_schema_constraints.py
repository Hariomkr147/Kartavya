"""Schema-level invariants that SQLite cannot enforce but PostgreSQL does.

The whole test suite runs on SQLite, so a schema mistake that SQLite tolerates
reaches production unseen. These assertions are about the metadata itself and
hold on every engine, which is the point: they fail here rather than in a
deploy log.
"""

from __future__ import annotations

from collections import Counter

from sqlalchemy.schema import CheckConstraint

import app.models  # noqa: F401  - importing registers every mapper
from app.extensions import db


def test_no_table_declares_two_constraints_with_the_same_name():
    """PostgreSQL requires constraint names to be unique within a table.

    A CHECK generated by an Enum is named after the ENUM, not the column, and
    the `ck` convention is ck_<table>_<constraint_name>. So two columns of the
    same enum type in one table silently collide.

    SQLite accepts the duplicate and the suite stays green; PostgreSQL rejects
    the CREATE TABLE with "check constraint ... already exists" and the deploy
    dies partway through the migration. That is exactly what happened to
    status_history (from_status and to_status are both ComplaintStatus), and it
    only surfaced on Neon.

    The fix is a distinct `name=` on enum_column for each such column.
    """
    collisions: dict[str, list[str]] = {}

    for table in db.metadata.sorted_tables:
        # `is not None` is not enough: SQLAlchemy marks an unnamed constraint
        # with a _NoneName sentinel rather than None, and several of those in
        # one table would look like a collision. They are named by the database
        # at creation time, so they cannot collide.
        named = [c.name for c in table.constraints if isinstance(c.name, str)]
        duplicates = sorted(name for name, count in Counter(named).items() if count > 1)
        if duplicates:
            collisions[table.name] = duplicates

    assert collisions == {}, (
        "Constraint names must be unique within a table or PostgreSQL rejects "
        f"the CREATE TABLE: {collisions}. Give each column its own "
        "enum_column(..., name=...)."
    )


def test_status_history_keeps_its_two_status_checks_apart():
    """A regression lock on the specific collision that broke a deploy."""
    table = db.metadata.tables["status_history"]
    check_names = {c.name for c in table.constraints if isinstance(c, CheckConstraint)}

    assert "ck_status_history_from_status" in check_names
    assert "ck_status_history_to_status" in check_names
    # The old, colliding name must not come back.
    assert "ck_status_history_complaintstatus" not in check_names
